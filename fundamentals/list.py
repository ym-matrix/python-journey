# A list can contain different data types.
list = ["hello", 123, "123", 2.30]

# Print the number of items in the list.
print(len(list))

# Print elements from index 0 up to index 1.
print(list[0:2])

# Print the item at index 2.
print(list[2])

# Concatenate the list with another list.
print(list + [7, 8, 9])

# Count how many times 123 appears in the list.
print(list.count(123))